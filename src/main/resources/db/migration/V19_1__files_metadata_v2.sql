PROMPT ============ V19_1.4 Backfill ============

UPDATE SYS_ATTACHED_FILES
   SET STATUS = 'DELETED'
 WHERE IS_DELETED = 1
   AND STATUS NOT IN ('DELETED', 'PURGED');

UPDATE SYS_ATTACHED_FILES
   SET FILE_EXT = LOWER(SUBSTR(ORIGINAL_NAME, INSTR(ORIGINAL_NAME, '.', -1) + 1))
 WHERE FILE_EXT IS NULL
   AND INSTR(ORIGINAL_NAME, '.', -1) > 0
   AND LENGTH(SUBSTR(ORIGINAL_NAME, INSTR(ORIGINAL_NAME, '.', -1) + 1)) BETWEEN 1 AND 10
   AND REGEXP_LIKE(SUBSTR(ORIGINAL_NAME, INSTR(ORIGINAL_NAME, '.', -1) + 1), '^[A-Za-z0-9]+$');

UPDATE SYS_ATTACHED_FILES f
   SET f.OWNER_STUDENT_ID = f.REFERENCE_ID
 WHERE f.OWNER_STUDENT_ID IS NULL
   AND f.MODULE_NAME = 'STUDENT'
   AND f.REFERENCE_ID IS NOT NULL
   AND EXISTS (SELECT 1 FROM EDU_STUDENTS s WHERE s.ID = f.REFERENCE_ID);

COMMIT;

