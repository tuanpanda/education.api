DECLARE
    V_COUNT   NUMBER;
    V_MISSING VARCHAR2(4000);
BEGIN
    SELECT COUNT(*) INTO V_COUNT
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'SYS_ATTACHED_FILES'
       AND COLUMN_NAME IN ('STATUS', 'UPLOADED_BY_USER_ID', 'UPLOADED_BY_TYPE', 'OWNER_STUDENT_ID', 'FILE_EXT',
                           'CHECKSUM_SHA256', 'STORAGE_BACKEND', 'SCAN_STATUS', 'SCANNED_AT', 'SCAN_DETAIL',
                           'DELETED_AT', 'DELETED_BY', 'DELETE_REASON', 'PURGE_AFTER', 'PURGED_AT');
    IF V_COUNT <> 15 THEN
        V_MISSING := V_MISSING || ' COLUMNS(' || V_COUNT || '/15)';
    END IF;

    SELECT COUNT(*) INTO V_COUNT
      FROM USER_CONSTRAINTS
     WHERE TABLE_NAME = 'SYS_ATTACHED_FILES'
       AND CONSTRAINT_NAME IN ('CK_FILES_STATUS', 'CK_FILES_SCAN_STATUS', 'CK_FILES_UPLOADER_TYPE',
                               'CK_FILES_STORAGE_BACKEND', 'CK_FILES_DELETED_SYNC', 'FK_FILES_UPLOADER',
                               'FK_FILES_OWNER_STUDENT')
       AND STATUS = 'ENABLED';
    IF V_COUNT <> 7 THEN
        V_MISSING := V_MISSING || ' CONSTRAINTS(' || V_COUNT || '/7)';
    END IF;

    SELECT COUNT(*) INTO V_COUNT
      FROM USER_INDEXES
     WHERE INDEX_NAME IN ('IDX_FILES_STATUS_CREATED', 'IDX_FILES_UPLOADER', 'IDX_FILES_OWNER_STUDENT',
                          'IDX_FILES_PURGE', 'IDX_FILES_CHECKSUM', 'IDX_FILES_MODULE_REF');
    IF V_COUNT <> 6 THEN
        V_MISSING := V_MISSING || ' INDEXES(' || V_COUNT || '/6)';
    END IF;

    SELECT COUNT(*) INTO V_COUNT
      FROM USER_OBJECTS
     WHERE OBJECT_NAME = 'PRC_GET_FILES_BY_REF' AND OBJECT_TYPE = 'PROCEDURE' AND STATUS = 'VALID';
    IF V_COUNT <> 1 THEN
        V_MISSING := V_MISSING || ' PRC_GET_FILES_BY_REF(INVALID)';
    END IF;

    IF V_MISSING IS NOT NULL THEN
        RAISE_APPLICATION_ERROR(-20002, 'V19_1: thieu / khong hop le:' || V_MISSING);
    END IF;

    FOR r IN (SELECT STATUS, COUNT(*) CNT, NVL(SUM(FILE_SIZE), 0) BYTES
                FROM SYS_ATTACHED_FILES GROUP BY STATUS ORDER BY STATUS) LOOP
        DBMS_OUTPUT.PUT_LINE('  STATUS=' || RPAD(r.STATUS, 10) || ' ' || r.CNT || ' file, ' || r.BYTES || ' byte');
    END LOOP;
    SELECT COUNT(*) INTO V_COUNT FROM SYS_ATTACHED_FILES WHERE CHECKSUM_SHA256 IS NULL;
    DBMS_OUTPUT.PUT_LINE('  Chua co checksum: ' || V_COUNT || ' file (chay "Tinh checksum" tren man Quan ly file)');
    DBMS_OUTPUT.PUT_LINE('  V19_1                                   OK');
END;
