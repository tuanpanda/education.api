DECLARE
    PROCEDURE ENSURE_CONSTRAINT(P_NAME VARCHAR2, P_DDL VARCHAR2) IS
        V_COUNT NUMBER;
    BEGIN
        SELECT COUNT(*) INTO V_COUNT
          FROM USER_CONSTRAINTS
         WHERE TABLE_NAME = 'SYS_ATTACHED_FILES' AND CONSTRAINT_NAME = P_NAME;
        IF V_COUNT = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE SYS_ATTACHED_FILES ADD CONSTRAINT ' || P_NAME || ' ' || P_DDL;
            DBMS_OUTPUT.PUT_LINE('  ' || RPAD(P_NAME, 40) || 'created');
        ELSE
            DBMS_OUTPUT.PUT_LINE('  ' || RPAD(P_NAME, 40) || 'already exists');
        END IF;
    END;
BEGIN
    ENSURE_CONSTRAINT('CK_FILES_STATUS',
        q'[CHECK (STATUS IN ('ACTIVE', 'PENDING', 'DELETED', 'PURGED'))]');
    ENSURE_CONSTRAINT('CK_FILES_SCAN_STATUS',
        q'[CHECK (SCAN_STATUS IN ('SKIPPED', 'PENDING', 'CLEAN', 'INFECTED', 'ERROR'))]');
    ENSURE_CONSTRAINT('CK_FILES_UPLOADER_TYPE',
        q'[CHECK (UPLOADED_BY_TYPE IS NULL OR UPLOADED_BY_TYPE IN ('STAFF', 'STUDENT', 'SYSTEM'))]');
    ENSURE_CONSTRAINT('CK_FILES_STORAGE_BACKEND',
        q'[CHECK (STORAGE_BACKEND IN ('LOCAL', 'S3'))]');
    ENSURE_CONSTRAINT('CK_FILES_DELETED_SYNC',
        q'[CHECK ((STATUS IN ('DELETED', 'PURGED') AND IS_DELETED = 1)
               OR (STATUS IN ('ACTIVE', 'PENDING') AND IS_DELETED = 0))]');
    ENSURE_CONSTRAINT('FK_FILES_UPLOADER',
        'FOREIGN KEY (UPLOADED_BY_USER_ID) REFERENCES SYS_USERS (ID)');
    ENSURE_CONSTRAINT('FK_FILES_OWNER_STUDENT',
        'FOREIGN KEY (OWNER_STUDENT_ID) REFERENCES EDU_STUDENTS (ID)');
END;
