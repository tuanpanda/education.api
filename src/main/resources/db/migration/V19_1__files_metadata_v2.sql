DECLARE
    V_CHAR_USED USER_TAB_COLUMNS.CHAR_USED%TYPE;
    V_LEN       NUMBER;
BEGIN
    SELECT CHAR_USED, CHAR_LENGTH INTO V_CHAR_USED, V_LEN
      FROM USER_TAB_COLUMNS
