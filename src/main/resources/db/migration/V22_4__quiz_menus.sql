DECLARE
    V_NAME  SYS_MENUS.MENU_NAME%TYPE;
    V_COUNT NUMBER;
BEGIN
    SELECT MENU_NAME INTO V_NAME FROM SYS_MENUS WHERE MENU_CODE = 'MENU_QUESTION_BANK' AND IS_DELETED = 0;
    IF V_NAME IS NULL OR V_NAME <> UNISTR('Ng\00E2n h\00E0ng c\00E2u h\1ECFi') THEN
        RAISE_APPLICATION_ERROR(-20005, 'V22_4: ten menu MENU_QUESTION_BANK khong khop UNISTR');
    END IF;
    SELECT MENU_NAME INTO V_NAME FROM SYS_MENUS WHERE MENU_CODE = 'MENU_QUIZ' AND IS_DELETED = 0;
    IF V_NAME IS NULL OR V_NAME <> UNISTR('Ki\1EC3m tra') THEN
        RAISE_APPLICATION_ERROR(-20006, 'V22_4: ten menu MENU_QUIZ khong khop UNISTR');
    END IF;

    SELECT COUNT(*) INTO V_COUNT
      FROM SYS_FUNCTIONS f
      JOIN SYS_MENUS m ON m.ID = f.MENU_ID AND m.MENU_CODE IN ('MENU_QUESTION_BANK', 'MENU_QUIZ')
     WHERE f.IS_DELETED = 0;
    IF V_COUNT <> 10 THEN
        RAISE_APPLICATION_ERROR(-20007, 'V22_4: co ' || V_COUNT || '/10 chuc nang');
    END IF;

    SELECT COUNT(*) INTO V_COUNT
      FROM SYS_ROLE_MENU_PERMISSIONS p
      JOIN SYS_MENUS m ON m.ID = p.MENU_ID AND m.MENU_CODE = 'MENU_QUIZ'
      JOIN SYS_ROLES r ON r.ID = p.ROLE_ID AND r.ROLE_CODE = 'ROLE_TEACHER'
     WHERE INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',VIEW,') > 0
       AND INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',GRADE,') > 0
       AND INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',DELETE,') = 0;
    IF V_COUNT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20008, 'V22_4: ROLE_TEACHER chua dung quyen MENU_QUIZ');
    END IF;

    SELECT COUNT(*) INTO V_COUNT
      FROM SYS_ROLE_MENU_PERMISSIONS p
      JOIN SYS_MENUS m ON m.ID = p.MENU_ID AND m.MENU_CODE IN ('MENU_QUESTION_BANK', 'MENU_QUIZ')
      JOIN SYS_ROLES r ON r.ID = p.ROLE_ID AND r.ROLE_CODE = 'ROLE_ADMIN'
     WHERE INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',DELETE,') > 0;
    IF V_COUNT <> 2 THEN
        RAISE_APPLICATION_ERROR(-20009, 'V22_4: ROLE_ADMIN chua du quyen');
    END IF;

    SELECT COUNT(*) INTO V_COUNT FROM USER_INDEXES
     WHERE INDEX_NAME = 'UX_GRADES_QUIZ_STUDENT' AND UNIQUENESS = 'UNIQUE' AND STATUS = 'VALID';
    IF V_COUNT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20010, 'V22_4: UX_GRADES_QUIZ_STUDENT khong hop le');
    END IF;
    DBMS_OUTPUT.PUT_LINE('  MENU_QUESTION_BANK, MENU_QUIZ, EDU_GRADES.QUIZ_ID OK');
END;
