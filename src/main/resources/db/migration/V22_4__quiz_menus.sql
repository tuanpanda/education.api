MERGE INTO SYS_FUNCTIONS t
USING (
    SELECT m.ID AS MENU_ID, x.FUNCTION_CODE, x.FUNCTION_NAME
      FROM SYS_MENUS m
      JOIN (
            SELECT 'VIEW' FUNCTION_CODE, UNISTR('Xem danh s\00E1ch') FUNCTION_NAME, 0 QUIZ_ONLY FROM DUAL UNION ALL
            SELECT 'CREATE', UNISTR('Th\00EAm m\1EDBi'), 0 FROM DUAL UNION ALL
            SELECT 'UPDATE', UNISTR('C\1EADp nh\1EADt'), 0 FROM DUAL UNION ALL
            SELECT 'DELETE', UNISTR('X\00F3a'), 0 FROM DUAL UNION ALL
            SELECT 'GRADE', UNISTR('Ch\1EA5m b\00E0i'), 1 FROM DUAL UNION ALL
            SELECT 'EXPORT', UNISTR('Xu\1EA5t Excel'), 1 FROM DUAL
           ) x ON (x.QUIZ_ONLY = 0 OR m.MENU_CODE = 'MENU_QUIZ')
     WHERE m.MENU_CODE IN ('MENU_QUESTION_BANK', 'MENU_QUIZ')
       AND m.IS_DELETED = 0
) s ON (t.MENU_ID = s.MENU_ID AND t.FUNCTION_CODE = s.FUNCTION_CODE)
WHEN MATCHED THEN UPDATE SET t.FUNCTION_NAME = s.FUNCTION_NAME, t.IS_DELETED = 0
WHEN NOT MATCHED THEN INSERT (ID, MENU_ID, FUNCTION_CODE, FUNCTION_NAME, IS_DELETED)
                      VALUES (SEQ_SYS_FUNCTIONS.NEXTVAL, s.MENU_ID, s.FUNCTION_CODE, s.FUNCTION_NAME, 0);

