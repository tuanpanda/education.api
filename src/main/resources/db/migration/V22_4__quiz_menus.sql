DECLARE
    V_COUNT NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_COUNT FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'EDU_GRADES' AND COLUMN_NAME = 'QUIZ_ID';
    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE EDU_GRADES ADD (QUIZ_ID NUMBER)';
        DBMS_OUTPUT.PUT_LINE('  EDU_GRADES.QUIZ_ID                      added');
    ELSE
        DBMS_OUTPUT.PUT_LINE('  EDU_GRADES.QUIZ_ID                      already exists');
    END IF;
    SELECT COUNT(*) INTO V_COUNT FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME = 'FK_GRADES_QUIZ';
    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE EDU_GRADES ADD CONSTRAINT FK_GRADES_QUIZ '
                       || 'FOREIGN KEY (QUIZ_ID) REFERENCES LMS_QUIZZES (ID)';
        DBMS_OUTPUT.PUT_LINE('  FK_GRADES_QUIZ                          created');
    ELSE
        DBMS_OUTPUT.PUT_LINE('  FK_GRADES_QUIZ                          already exists');
    END IF;
    SELECT COUNT(*) INTO V_COUNT FROM USER_INDEXES WHERE INDEX_NAME = 'UX_GRADES_QUIZ_STUDENT';
    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UX_GRADES_QUIZ_STUDENT ON EDU_GRADES ('
            || 'CASE WHEN QUIZ_ID IS NOT NULL AND IS_DELETED = 0 THEN QUIZ_ID END, '
            || 'CASE WHEN QUIZ_ID IS NOT NULL AND IS_DELETED = 0 THEN STUDENT_ID END)';
        DBMS_OUTPUT.PUT_LINE('  UX_GRADES_QUIZ_STUDENT                  created');
    ELSE
        DBMS_OUTPUT.PUT_LINE('  UX_GRADES_QUIZ_STUDENT                  already exists');
    END IF;
END;
