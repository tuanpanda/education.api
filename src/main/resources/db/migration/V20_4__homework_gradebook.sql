WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET DEFINE OFF
SET SERVEROUTPUT ON SIZE UNLIMITED

PROMPT ============ V20_4.1 Kiem tra truoc ============

DECLARE
    V_COUNT NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_COUNT FROM USER_TABLES WHERE TABLE_NAME IN ('EDU_GRADES', 'LMS_ASSIGNMENTS');
    IF V_COUNT <> 2 THEN
        RAISE_APPLICATION_ERROR(-20001, 'V20_4: thieu EDU_GRADES / LMS_ASSIGNMENTS (chay V20_1 truoc)');
    END IF;
    SELECT COUNT(*) INTO V_COUNT FROM USER_CONSTRAINTS
     WHERE TABLE_NAME = 'EDU_GRADES' AND CONSTRAINT_NAME = 'CK_GRADES_TYPE'
       AND SEARCH_CONDITION_VC LIKE '%''ASSIGNMENT''%';
    IF V_COUNT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20002, 'V20_4: CK_GRADES_TYPE khong con cho phep ASSIGNMENT');
    END IF;
    DBMS_OUTPUT.PUT_LINE('  EDU_GRADES, LMS_ASSIGNMENTS, CK_GRADES_TYPE OK');
END;
/

PROMPT ============ V20_4.2 Cot ASSIGNMENT_ID ============

DECLARE
    V_COUNT NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_COUNT FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'EDU_GRADES' AND COLUMN_NAME = 'ASSIGNMENT_ID';
    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE EDU_GRADES ADD (ASSIGNMENT_ID NUMBER)';
        DBMS_OUTPUT.PUT_LINE('  EDU_GRADES.ASSIGNMENT_ID                added');
    ELSE
        DBMS_OUTPUT.PUT_LINE('  EDU_GRADES.ASSIGNMENT_ID                already exists');
    END IF;
    SELECT COUNT(*) INTO V_COUNT FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME = 'FK_GRADES_ASSIGNMENT';
    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE EDU_GRADES ADD CONSTRAINT FK_GRADES_ASSIGNMENT '
                       || 'FOREIGN KEY (ASSIGNMENT_ID) REFERENCES LMS_ASSIGNMENTS (ID)';
        DBMS_OUTPUT.PUT_LINE('  FK_GRADES_ASSIGNMENT                    created');
    ELSE
        DBMS_OUTPUT.PUT_LINE('  FK_GRADES_ASSIGNMENT                    already exists');
    END IF;
END;
/

COMMENT ON COLUMN EDU_GRADES.ASSIGNMENT_ID IS 'GD2: diem day tu LMS_ASSIGNMENTS (GRADE_TYPE=ASSIGNMENT); NULL = nhap tay';

PROMPT ============ V20_4.3 Unique index ============

DECLARE
    V_COUNT NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_COUNT FROM USER_INDEXES WHERE INDEX_NAME = 'UX_GRADES_ASSIGNMENT_STUDENT';
    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UX_GRADES_ASSIGNMENT_STUDENT ON EDU_GRADES ('
            || 'CASE WHEN ASSIGNMENT_ID IS NOT NULL AND IS_DELETED = 0 THEN ASSIGNMENT_ID END, '
            || 'CASE WHEN ASSIGNMENT_ID IS NOT NULL AND IS_DELETED = 0 THEN STUDENT_ID END)';
        DBMS_OUTPUT.PUT_LINE('  UX_GRADES_ASSIGNMENT_STUDENT            created');
    ELSE
        DBMS_OUTPUT.PUT_LINE('  UX_GRADES_ASSIGNMENT_STUDENT            already exists');
    END IF;
END;
/

PROMPT ============ V20_4.4 Kiem tra sau ============

DECLARE
    V_COUNT NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_COUNT FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'EDU_GRADES' AND COLUMN_NAME = 'ASSIGNMENT_ID' AND NULLABLE = 'Y';
    IF V_COUNT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20003, 'V20_4: thieu cot EDU_GRADES.ASSIGNMENT_ID (nullable)');
    END IF;
    SELECT COUNT(*) INTO V_COUNT FROM USER_INDEXES
     WHERE INDEX_NAME = 'UX_GRADES_ASSIGNMENT_STUDENT' AND UNIQUENESS = 'UNIQUE' AND STATUS = 'VALID';
    IF V_COUNT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20004, 'V20_4: UX_GRADES_ASSIGNMENT_STUDENT khong hop le');
    END IF;
    SELECT COUNT(*) INTO V_COUNT FROM USER_CONSTRAINTS
     WHERE CONSTRAINT_NAME = 'FK_GRADES_ASSIGNMENT' AND STATUS = 'ENABLED';
    IF V_COUNT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20005, 'V20_4: FK_GRADES_ASSIGNMENT khong hop le');
    END IF;
    DBMS_OUTPUT.PUT_LINE('  EDU_GRADES.ASSIGNMENT_ID                OK');
END;
/

COMMIT;

