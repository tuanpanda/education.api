DECLARE
    V_COUNT NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_COUNT FROM USER_TABLES WHERE TABLE_NAME = 'LMS_SUBMISSIONS';
    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE LMS_SUBMISSIONS (
                ID                  NUMBER                              NOT NULL,
                ASSIGNMENT_ID       NUMBER                              NOT NULL,
                STUDENT_ID          NUMBER                              NOT NULL,
                CONTENT_TEXT        CLOB,
                STATUS              VARCHAR2(20)   DEFAULT 'DRAFT'      NOT NULL,
                ATTEMPT_COUNT       NUMBER(3)      DEFAULT 0            NOT NULL,
                FIRST_SUBMITTED_AT  TIMESTAMP,
                SUBMITTED_AT        TIMESTAMP,
                IS_LATE             NUMBER(1)      DEFAULT 0            NOT NULL,
                SCORE               NUMBER(5,2),
                FEEDBACK            CLOB,
                GRADED_BY           NUMBER,
                GRADED_AT           TIMESTAMP,
                RETURNED_AT         TIMESTAMP,
                RETURN_REASON       VARCHAR2(500 CHAR),
                VERSION             NUMBER(10)     DEFAULT 0            NOT NULL,
                IS_DELETED          NUMBER(1)      DEFAULT 0            NOT NULL,
                CREATED_AT          TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
                UPDATED_AT          TIMESTAMP,
                CREATED_BY          VARCHAR2(50),
                UPDATED_BY          VARCHAR2(50),
                CONSTRAINT PK_LMS_SUBMISSIONS PRIMARY KEY (ID),
                CONSTRAINT UQ_SUB_ASG_STUDENT UNIQUE (ASSIGNMENT_ID, STUDENT_ID),
                CONSTRAINT FK_SUB_ASSIGNMENT FOREIGN KEY (ASSIGNMENT_ID) REFERENCES LMS_ASSIGNMENTS (ID),
                CONSTRAINT FK_SUB_STUDENT    FOREIGN KEY (STUDENT_ID)    REFERENCES EDU_STUDENTS (ID),
                CONSTRAINT FK_SUB_GRADED_BY  FOREIGN KEY (GRADED_BY)     REFERENCES SYS_USERS (ID),
                CONSTRAINT CK_SUB_STATUS CHECK (STATUS IN ('DRAFT', 'SUBMITTED', 'RETURNED', 'GRADED')),
                CONSTRAINT CK_SUB_FLAGS  CHECK (IS_LATE IN (0, 1) AND IS_DELETED IN (0, 1)),
                CONSTRAINT CK_SUB_SCORE  CHECK (SCORE IS NULL OR SCORE >= 0),
                CONSTRAINT CK_SUB_GRADED CHECK (STATUS <> 'GRADED' OR (SCORE IS NOT NULL AND GRADED_AT IS NOT NULL))
            )]';
        DBMS_OUTPUT.PUT_LINE('  LMS_SUBMISSIONS                         created');
    ELSE
        DBMS_OUTPUT.PUT_LINE('  LMS_SUBMISSIONS                         already exists');
    END IF;
END;
/

