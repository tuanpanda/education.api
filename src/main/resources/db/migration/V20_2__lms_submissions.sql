DECLARE
    V_MISSING VARCHAR2(4000);
    V_COUNT   NUMBER;
BEGIN
    FOR r IN (SELECT n.OBJECT_NAME, n.OBJECT_TYPE, NVL(o.STATUS, 'MISSING') STATUS
                FROM (SELECT 'LMS_SUBMISSIONS' OBJECT_NAME, 'TABLE' OBJECT_TYPE FROM DUAL UNION ALL
                      SELECT 'LMS_SUBMISSION_HISTORY', 'TABLE' FROM DUAL UNION ALL
                      SELECT 'SEQ_LMS_SUBMISSIONS', 'SEQUENCE' FROM DUAL UNION ALL
                      SELECT 'SEQ_LMS_SUBMISSION_HISTORY', 'SEQUENCE' FROM DUAL UNION ALL
                      SELECT 'IX_SUB_STUDENT_STATUS', 'INDEX' FROM DUAL UNION ALL
                      SELECT 'IX_SUB_ASSIGNMENT_STATUS', 'INDEX' FROM DUAL) n
                LEFT JOIN USER_OBJECTS o ON o.OBJECT_NAME = n.OBJECT_NAME AND o.OBJECT_TYPE = n.OBJECT_TYPE) LOOP
        DBMS_OUTPUT.PUT_LINE('  ' || RPAD(r.OBJECT_NAME, 40) || r.STATUS);
        IF r.STATUS <> 'VALID' THEN
            V_MISSING := V_MISSING || ' ' || r.OBJECT_NAME;
        END IF;
    END LOOP;
    SELECT COUNT(*) INTO V_COUNT FROM USER_CONSTRAINTS
     WHERE STATUS = 'ENABLED'
       AND CONSTRAINT_NAME IN ('UQ_SUB_ASG_STUDENT', 'CK_SUB_STATUS', 'CK_SUB_GRADED', 'UQ_SUBH_ATTEMPT');
    IF V_COUNT <> 4 THEN
        V_MISSING := V_MISSING || ' SUBMISSION_CONSTRAINTS';
    END IF;
    IF V_MISSING IS NOT NULL THEN
        RAISE_APPLICATION_ERROR(-20009, 'V20_2: thieu/khong hop le:' || V_MISSING);
    END IF;
END;
/

