    SELECT 'STUDENT_IMPORT', 5242880, NULL, NULL, 'xlsx', 0, 1 FROM DUAL UNION ALL
    SELECT 'CLASS', 20971520, 30, 209715200, NULL, 0, 1 FROM DUAL UNION ALL
