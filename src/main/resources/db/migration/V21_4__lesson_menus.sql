DECLARE
    V_NAME  SYS_MENUS.MENU_NAME%TYPE;
    V_COUNT NUMBER;
BEGIN
    SELECT MENU_NAME INTO V_NAME FROM SYS_MENUS WHERE MENU_CODE = 'MENU_COURSE' AND IS_DELETED = 0;
    IF V_NAME IS NULL OR V_NAME <> UNISTR('Kh\00F3a h\1ECDc') THEN
        RAISE_APPLICATION_ERROR(-20004, 'V21_4: ten menu MENU_COURSE khong khop UNISTR');
    END IF;
    SELECT MENU_NAME INTO V_NAME FROM SYS_MENUS WHERE MENU_CODE = 'MENU_LESSON' AND IS_DELETED = 0;
    IF V_NAME IS NULL OR V_NAME <> UNISTR('H\1ECDc li\1EC7u') THEN
        RAISE_APPLICATION_ERROR(-20005, 'V21_4: ten menu MENU_LESSON khong khop UNISTR');
    END IF;

    SELECT COUNT(*) INTO V_COUNT
      FROM SYS_FUNCTIONS f
      JOIN SYS_MENUS m ON m.ID = f.MENU_ID AND m.MENU_CODE IN ('MENU_COURSE', 'MENU_LESSON')
     WHERE f.IS_DELETED = 0
       AND f.FUNCTION_CODE IN ('VIEW', 'CREATE', 'UPDATE', 'DELETE');
    IF V_COUNT <> 8 THEN
        RAISE_APPLICATION_ERROR(-20006, 'V21_4: co ' || V_COUNT || '/8 chuc nang');
    END IF;

    SELECT COUNT(*) INTO V_COUNT
      FROM SYS_ROLE_MENU_PERMISSIONS p
      JOIN SYS_MENUS m ON m.ID = p.MENU_ID AND m.MENU_CODE = 'MENU_COURSE'
      JOIN SYS_ROLES r ON r.ID = p.ROLE_ID AND r.ROLE_CODE = 'ROLE_ADMIN'
     WHERE INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',VIEW,') > 0
       AND INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',CREATE,') > 0
       AND INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',UPDATE,') > 0
       AND INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',DELETE,') > 0;
    IF V_COUNT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20007, 'V21_4: ROLE_ADMIN chua du quyen MENU_COURSE');
    END IF;

    SELECT COUNT(*) INTO V_COUNT
      FROM SYS_ROLE_MENU_PERMISSIONS p
      JOIN SYS_MENUS m ON m.ID = p.MENU_ID AND m.MENU_CODE = 'MENU_LESSON'
      JOIN SYS_ROLES r ON r.ID = p.ROLE_ID AND r.ROLE_CODE = 'ROLE_ADMIN'
     WHERE INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',VIEW,') > 0
       AND INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',CREATE,') > 0
       AND INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',UPDATE,') > 0
       AND INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',DELETE,') > 0;
    IF V_COUNT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20008, 'V21_4: ROLE_ADMIN chua du quyen MENU_LESSON');
    END IF;

    SELECT COUNT(*) INTO V_COUNT
      FROM SYS_ROLE_MENU_PERMISSIONS p
      JOIN SYS_MENUS m ON m.ID = p.MENU_ID AND m.MENU_CODE = 'MENU_LESSON'
      JOIN SYS_ROLES r ON r.ID = p.ROLE_ID AND r.ROLE_CODE = 'ROLE_TEACHER'
     WHERE INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',VIEW,') > 0
       AND INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',UPDATE,') > 0
       AND INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',DELETE,') = 0;
    IF V_COUNT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20009, 'V21_4: ROLE_TEACHER chua dung quyen MENU_LESSON');
    END IF;

    SELECT COUNT(*) INTO V_COUNT
      FROM SYS_ROLE_MENU_PERMISSIONS p
      JOIN SYS_MENUS m ON m.ID = p.MENU_ID AND m.MENU_CODE = 'MENU_COURSE'
      JOIN SYS_ROLES r ON r.ID = p.ROLE_ID AND r.ROLE_CODE = 'ROLE_TEACHER'
     WHERE p.ALLOWED_FUNCTIONS = 'VIEW';
    IF V_COUNT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20010, 'V21_4: ROLE_TEACHER phai chi co VIEW tren MENU_COURSE');
    END IF;

    SELECT COUNT(*) INTO V_COUNT FROM SYS_FILE_MODULE_SETTINGS
     WHERE MODULE_NAME = 'LESSON' AND INSTR(',' || LOWER(ALLOWED_EXTENSIONS) || ',', ',zip,') = 0;
    IF V_COUNT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20011, 'V21_4: thieu module file LESSON (hoac LESSON cho zip)');
    END IF;
    DBMS_OUTPUT.PUT_LINE('  MENU_COURSE, MENU_LESSON, module LESSON OK');
END;
