DECLARE
    V_NAME  SYS_MENUS.MENU_NAME%TYPE;
    V_COUNT NUMBER;
BEGIN
    SELECT MENU_NAME INTO V_NAME FROM SYS_MENUS WHERE MENU_CODE = 'MENU_HOMEWORK' AND IS_DELETED = 0;
    IF V_NAME IS NULL OR V_NAME <> UNISTR('B\00E0i t\1EADp') THEN
        RAISE_APPLICATION_ERROR(-20005, 'V20_3: ten menu MENU_HOMEWORK khong khop UNISTR');
    END IF;

    SELECT COUNT(*) INTO V_COUNT
      FROM SYS_FUNCTIONS f
      JOIN SYS_MENUS m ON m.ID = f.MENU_ID AND m.MENU_CODE = 'MENU_HOMEWORK'
     WHERE f.IS_DELETED = 0
       AND f.FUNCTION_CODE IN ('VIEW', 'CREATE', 'UPDATE', 'DELETE', 'GRADE', 'EXPORT');
    IF V_COUNT <> 6 THEN
        RAISE_APPLICATION_ERROR(-20006, 'V20_3: MENU_HOMEWORK co ' || V_COUNT || '/6 chuc nang');
    END IF;

    SELECT COUNT(*) INTO V_COUNT
      FROM SYS_ROLE_MENU_PERMISSIONS p
      JOIN SYS_MENUS m ON m.ID = p.MENU_ID AND m.MENU_CODE = 'MENU_HOMEWORK'
      JOIN SYS_ROLES r ON r.ID = p.ROLE_ID AND r.ROLE_CODE = 'ROLE_ADMIN'
     WHERE INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',VIEW,') > 0
       AND INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',CREATE,') > 0
       AND INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',UPDATE,') > 0
       AND INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',DELETE,') > 0
       AND INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',GRADE,') > 0
       AND INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',EXPORT,') > 0;
    IF V_COUNT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20007, 'V20_3: ROLE_ADMIN chua du quyen MENU_HOMEWORK');
    END IF;

    SELECT COUNT(*) INTO V_COUNT
      FROM SYS_ROLE_MENU_PERMISSIONS p
      JOIN SYS_MENUS m ON m.ID = p.MENU_ID AND m.MENU_CODE = 'MENU_HOMEWORK'
      JOIN SYS_ROLES r ON r.ID = p.ROLE_ID AND r.ROLE_CODE = 'ROLE_TEACHER'
     WHERE INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',VIEW,') > 0
       AND INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',GRADE,') > 0
       AND INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',EXPORT,') > 0
       AND INSTR(',' || p.ALLOWED_FUNCTIONS || ',', ',DELETE,') = 0;
    IF V_COUNT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20008, 'V20_3: ROLE_TEACHER chua dung quyen MENU_HOMEWORK');
    END IF;

    SELECT COUNT(*) INTO V_COUNT FROM SYS_FILE_MODULE_SETTINGS
     WHERE MODULE_NAME IN ('ASSIGNMENT', 'SUBMISSION', 'FEEDBACK') AND IS_ACTIVE = 1;
    IF V_COUNT <> 3 THEN
        RAISE_APPLICATION_ERROR(-20009, 'V20_3: module file GD2 chua bat du (' || V_COUNT || '/3)');
    END IF;
    SELECT COUNT(*) INTO V_COUNT FROM SYS_FILE_MODULE_SETTINGS
     WHERE MODULE_NAME = 'SUBMISSION' AND INSTR(',' || LOWER(ALLOWED_EXTENSIONS) || ',', ',zip,') > 0;
    IF V_COUNT <> 0 THEN
        RAISE_APPLICATION_ERROR(-20010, 'V20_3: SUBMISSION khong duoc cho phep zip');
    END IF;
    DBMS_OUTPUT.PUT_LINE('  MENU_HOMEWORK + module file GD2         OK');
END;
