-- 1. Trigger TRG_EDU_STUDENTS_BI_CODE chi sinh ma khi STUDENT_CODE NULL
--    (import hang loat giu nguyen ma trong file Excel).
-- 2. Quyen IMPORT cho MENU_STUDENT_LIST.
--    ROLE_ADMIN: tat ca function cua menu.
--    ROLE_ADMISSION: VIEW,CREATE,IMPORT.
--
--   sqlplus EDUCATION/EDUCATION@//localhost:1521/ORCL @V8__student_excel_import.sql
